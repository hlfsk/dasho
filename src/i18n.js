export function t(key, fallback) {
  if (DICT[LANG] && DICT[LANG][key] != null) return DICT[LANG][key];
  if (DICT.ru[key] != null) return DICT.ru[key];
  return fallback != null ? fallback : key;
}

// Хелпер для перевода имени ноды по её registry-ключу.
// Возвращает русское оригинальное название если перевода нет.
export function tNode(typeName, originalTitle) {
  return t(`node.${typeName}.title`, originalTitle);
}
// Хелпер для перевода label сокета или параметра.
// path — `${typeName}.${kind}.${name}`, kind = 'in'|'out'|'param'
export function tField(path, original) {
  return t(`node.${path}`, original);
}
// Хелпер для перевода имени категории шаблонов и шаблона
export function tTplCat(cat) { return t(`tpl.cat.${cat}`, cat); }
export function tTplName(name) { return t(`tpl.name.${name}`, name); }
export function tTplDesc(desc) { return t(`tpl.desc.${desc}`, desc); }
